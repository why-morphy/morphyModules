DEFAULT_REACTIONS = ["👍", "❤️", "🔥", "🤔", "👀", "🆒"]
# Seconds of "typing…" per character of the reply, capped so long replies don't stall
TYPING_SPEED = 8
TYPING_MAX = 15


@loader.module("RandomReply", "archfemboy")
class RandomReplyMod(loader.Module):
    """Randomly reacts to and replies to messages in chosen groups"""

    strings = {
        "cfg_replies": "Replies to pick from. Leave empty to use the built-in list",
        "cfg_chance": "Reply to 1 in N messages. Bigger means rarer",
        "cfg_groups": "IDs of groups to reply in",
        "cfg_reactions": "Reactions to put on the message. Leave empty to skip reacting",
        "on": "✅ RandomReply is <b>on</b> in this chat",
        "off": "💤 RandomReply is <b>off</b> in this chat",
        "not_group": "🚫 Use this in a group",
    }

    strings_ru = {
        "cfg_replies": "Сообщения для ответов. Пусто — встроенный список",
        "cfg_chance": "Отвечать на 1 из N сообщений. Чем больше, тем реже",
        "cfg_groups": "ID групп, где отвечать",
        "cfg_reactions": "Реакции на сообщение. Пусто — без реакций",
        "on": "✅ RandomReply <b>включён</b> в этом чате",
        "off": "💤 RandomReply <b>выключен</b> в этом чате",
        "not_group": "🚫 Используй в группе",
    }

    def __init__(self):
        # Newest message id seen per chat. Shizu also feeds edits to watchers, and
        # Telegram reports reaction changes as edits, so without this every reaction
        # on a message (ours included) would roll the chance again
        self._last_seen: dict[int, int] = {}
        self.config = loader.ModuleConfig(
            loader.ConfigValue(
                "replies",
                [],
                lambda: self.strings("cfg_replies"),
                validator=loader.validators.Series(),
            ),
            loader.ConfigValue(
                "chance",
                15,
                lambda: self.strings("cfg_chance"),
                validator=loader.validators.Integer(minimum=1),
            ),
            loader.ConfigValue(
                "groups",
                [],
                lambda: self.strings("cfg_groups"),
                validator=loader.validators.Series(),
            ),
            loader.ConfigValue(
                "reactions",
                DEFAULT_REACTIONS,
                lambda: self.strings("cfg_reactions"),
                validator=loader.validators.Series(),
            ),
        )

    @loader.command()
    async def rrtoggle(self, app: Client, message: types.Message):
        """Turn random replies on or off in the current group"""
        if message.chat.type not in (enums.ChatType.GROUP, enums.ChatType.SUPERGROUP):
            return await utils.answer(message, self.strings("not_group"))

        chat_id = str(message.chat.id)
        groups = list(self.config["groups"])
        if chat_id in groups:
            groups.remove(chat_id)
            key = "off"
        else:
            groups.append(chat_id)
            key = "on"
        self.config["groups"] = groups
        await utils.answer(message, self.strings(key))

    @loader.watcher("in", "only_groups")
    async def watcher(self, app: Client, message: types.Message):
        if str(message.chat.id) not in self.config["groups"] or message.edit_date:
            return
        if message.id <= self._last_seen.get(message.chat.id, 0):
            return
        self._last_seen[message.chat.id] = message.id

        if random.randint(1, self.config["chance"]) != 1:
            return

        if self.config["reactions"]:
            try:
                await app.send_reaction(
                    message.chat.id,
                    message_id=message.id,
                    emoji=random.choice(self.config["reactions"]),
                )
            except Exception:
                # Reactions can be disabled or limited in the chat; still reply
                pass

        text = random.choice(self.config["replies"] or DEFAULT_REPLIES)
        await app.send_chat_action(message.chat.id, enums.ChatAction.TYPING)
        await asyncio.sleep(min(len(text) / TYPING_SPEED, TYPING_MAX))
        await message.reply(text, parse_mode=enums.ParseMode.DISABLED)
